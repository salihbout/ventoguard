import type { Brief } from "../lib/api";
import { Empty } from "./States";

// The brief is LLM output: label it as such, and show the model and the evidence it was grounded on.
export function AiBrief({ brief }: { brief: Brief | null }) {
  if (!brief) {
    return (
      <section className="panel">
        <Empty title="No maintenance brief for this turbine">Briefs are generated for turbines at medium risk or higher.</Empty>
      </section>
    );
  }
  const steps = brief.recommended_action.split(";").map((s) => s.trim()).filter(Boolean);
  return (
    <section className="panel brief" aria-labelledby="brief-title">
      <div className="brief-head">
        <h2 id="brief-title">{brief.headline}</h2>
        <span className="ai-label">
          <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="1.75" aria-hidden="true">
            <path d="M12 3v4M12 17v4M3 12h4M17 12h4M6.3 6.3l2.5 2.5M15.2 15.2l2.5 2.5M6.3 17.7l2.5-2.5M15.2 8.8l2.5-2.5" />
          </svg>
          AI-generated maintenance brief
        </span>
      </div>
      <p>{brief.diagnosis}</p>
      <div>
        <div className="fact-label" style={{ marginBottom: 8 }}>Recommended action, within {brief.urgency_days} {brief.urgency_days === 1 ? "day" : "days"}</div>
        <ol className="steps">{steps.map((s) => <li key={s}>{s}</li>)}</ol>
      </div>
      <p><strong>Crew and parts.</strong> {brief.crew_and_parts}</p>
      <p><strong>Business case.</strong> {brief.business_case}</p>
      <div className="provenance">
        Generated by <span className="mono">{brief.llm_endpoint}</span> with <span className="mono">ai_query</span> from the model score, 7-day sensor
        residuals against the fleet and recent technician notes · {new Date(brief.generated_at).toLocaleString("en-GB")}. Check before dispatch.
      </div>
    </section>
  );
}
